"""Reject refreshed-but-unchanged Mimir evidence using synthetic store replies."""

from types import SimpleNamespace
from uuid import UUID

import httpx
import pytest

from scripts import verify_api_telemetry as verifier


def metric_rows(value):
    """Return representative Prometheus counter/histogram-count samples."""
    return [
        {"metric": {"job": "unshaken-backend", "http_route": route,
                    "http_request_method": "GET", "http_response_status_code": status,
                    "failure_category": category},
         "value": [1, str(value * count)]}
        for (route, status, category), count in verifier.EXPECTED_INCREMENTS.items()
    ]


@pytest.mark.parametrize("before,after,expected", [
    ([], metric_rows(0), False),
    (metric_rows(5), metric_rows(5), False),
    (metric_rows(5), metric_rows(6), True),
    ([], metric_rows(1), True),
    (metric_rows(5), metric_rows(1), False),
    (metric_rows(5), [], False),
])
def test_observed_increments(before, after, expected):
    """Zero, unchanged, reset and missing series cannot prove new requests."""
    assert verifier._metrics_increased(before, after) is expected


@pytest.mark.parametrize("value", ["NaN", "Inf", "-1", "0.5"])
def test_invalid_metric_counts(value):
    """Malformed store samples fail closed instead of becoming false evidence."""
    rows = metric_rows(1)
    rows[0]["value"][1] = value
    with pytest.raises(ValueError):
        verifier._metrics_increased([], rows)


def test_unrelated_historical_failure_is_not_required_to_refresh():
    """A previous process's 503 series is not part of this run's expected set."""
    historical = metric_rows(1)[0]
    historical["metric"]["http_response_status_code"] = "503"
    historical["metric"]["failure_category"] = "database_unavailable"
    assert verifier._metrics_increased([historical], metric_rows(1))


@pytest.mark.parametrize("baseline,after,expected_exit", [(0, 0, 1), (5, 5, 1), (5, 6, 0), (0, 1, 0), (5, 1, 1)])
def test_main_requires_request_metric_increments(monkeypatch, capsys, baseline, after, expected_exit):
    """Run the whole verifier with otherwise valid HTTP/log/trace evidence.

    All network and DB boundaries are synthetic. Zero/unchanged cases used to
    print PASS; positive cases ensure the test does not simply force failure.
    """
    ids = {"success": str(UUID(int=1)), "failure": str(UUID(int=2)),
           "ready": str(UUID(int=3)), "live": str(UUID(int=4))}
    routes = {"success": "/api/v1/exercise-categories", "failure": "/api/v1/body-parts"}
    expected_rows = [{"id": 1, "name": "Synthetic", "sort_order": 1}]

    class Client:
        """Provide only the HTTP responses generated by this verifier."""
        def __init__(self, **kwargs):
            pass
        def __enter__(self):
            return self
        def __exit__(self, *args):
            pass
        def get(self, path, **kwargs):
            if path == "/health/live":
                kind, status, body = "live", 200, {"status": "alive"}
            elif path == "/health/ready":
                kind, status, body = "ready", 200, {"status": "ready"}
            elif path == routes["success"]:
                kind, status, body = "success", 200, {"items": expected_rows}
            else:
                kind, status, body = "failure", 422, {}
            return httpx.Response(status, json=body, headers={"x-request-id": ids[kind]})

    def logs(*args):
        """Supply request-specific metadata and two distinct synthetic traces."""
        return [{"metadata": {"request_id": ids[kind], "http.route": routes[kind],
                              "http.response.status_code": 200 if kind == "success" else 422,
                              "failure.category": "none" if kind == "success" else "invalid_request",
                              "trace_id": "a" * 32 if kind == "success" else "b" * 32},
                 "labels": {}, "line": "http.request.completed", "shape": ()}
                for kind in routes]

    def proxy(client, datasource, path, **kwargs):
        """Keep every non-metric acceptance gate valid for the isolated probe."""
        if datasource == "tempo":
            data = {"spans": [{"name": "database.read", "table": "exercise_categories"}]}
        elif path.endswith("/series"):
            data = {"data": [{"service_name": "unshaken-backend"}]}
        else:
            data = {"data": {"result": [{"stream": {}, "values": [
                ["1", "database_readiness.state_changed", {"request_id": ids["ready"]}]
            ]}]}}
        return httpx.Response(200, json=data)

    ticks = iter([0, 0, 46])
    monkeypatch.setattr(verifier, "time", SimpleNamespace(
        time_ns=lambda: 1, monotonic=lambda: next(ticks), sleep=lambda _: None))
    monkeypatch.setattr(verifier, "_validate_test_database", lambda: object())
    monkeypatch.setattr(verifier, "_verify_database_contents", lambda _: {"exercise_categories": expected_rows})
    monkeypatch.setattr(verifier, "dotenv_values", lambda _: {})
    monkeypatch.setenv("GRAFANA_ADMIN_USER", "synthetic")
    monkeypatch.setenv("GRAFANA_ADMIN_PASSWORD", "synthetic")
    monkeypatch.setattr(verifier.httpx, "Client", Client)
    monkeypatch.setattr(verifier, "_query_request_logs", logs)
    monkeypatch.setattr(verifier, "_proxy", proxy)
    monkeypatch.setattr(verifier, "_query_metric", lambda client, name, start: metric_rows(baseline if start == 0 else after))
    assert verifier.main() == expected_exit
    assert ("PASS:" in capsys.readouterr().out) is (expected_exit == 0)
